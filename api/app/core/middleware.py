"""Cross-cutting HTTP middleware: request-id propagation and security headers.

Mirrors the intent of `backend/apps/core/middleware.py` (same header names,
same request-id behavior) but is a fresh Starlette implementation — the two
services share no code, only the header contract.
"""
from __future__ import annotations

import logging
import uuid
from contextvars import ContextVar
from typing import Awaitable, Callable

from starlette.middleware.base import BaseHTTPMiddleware
from starlette.requests import Request
from starlette.responses import Response

from app.core.config import settings

logger = logging.getLogger("app")

REQUEST_ID_HEADER = "X-Request-ID"

_request_id_ctx_var: ContextVar[str] = ContextVar("request_id", default="-")


def generate_request_id() -> str:
    return uuid.uuid4().hex


def set_request_id(request_id: str) -> None:
    _request_id_ctx_var.set(request_id)


def get_request_id() -> str:
    return _request_id_ctx_var.get()


class RequestIDMiddleware(BaseHTTPMiddleware):
    """Generates (or propagates) an `X-Request-ID` for every HTTP response.

    - If the incoming request already carries an `X-Request-ID` header (e.g.
      set by an upstream proxy/load balancer), it is reused.
    - Otherwise a fresh uuid4 hex is generated.
    - The id is pushed into a contextvar (so the global exception handler can
      log and echo it even when it has no `Request` object at hand) and is
      always present on the response.
    """

    async def dispatch(
        self, request: Request, call_next: Callable[[Request], Awaitable[Response]]
    ) -> Response:
        incoming = request.headers.get(REQUEST_ID_HEADER)
        request_id = incoming or generate_request_id()
        set_request_id(request_id)
        request.state.request_id = request_id

        response = await call_next(request)
        response.headers[REQUEST_ID_HEADER] = request_id
        return response


CSP = "default-src 'none'; frame-ancestors 'none'; base-uri 'none'"


def apply_security_headers(response: Response) -> Response:
    """Applies the literal VAPT-spec security headers to a response in place.

    Shared by `SecurityHeadersMiddleware` (the normal path) AND
    `app.main.unhandled_exception_handler` (see that module for why): a
    response built by FastAPI's own `@app.exception_handler(Exception)` is
    generated by Starlette's `ServerErrorMiddleware`, which wraps *outside*
    every middleware added via `app.add_middleware(...)` — so an unhandled
    exception's response never passes back through `SecurityHeadersMiddleware
    .dispatch()` at all. Without calling this helper directly from the
    exception handler too, the one response that most needs hardened
    headers (a 500) would be the one response missing them. Verified live:
    see README.md "Verification" step 10.
    """
    response.headers["X-Content-Type-Options"] = "nosniff"
    response.headers["X-Frame-Options"] = "DENY"
    response.headers["Referrer-Policy"] = "no-referrer"
    response.headers["Cache-Control"] = "no-store"
    response.headers["X-XSS-Protection"] = "1; mode=block"
    response.headers["Content-Security-Policy"] = CSP

    # Never sent over plain http in local dev — a browser ignores it there
    # anyway, but sending it would be misleading/incorrect.
    if settings.is_production:
        response.headers["Strict-Transport-Security"] = (
            "max-age=31536000; includeSubDomains; preload"
        )

    return response


class SecurityHeadersMiddleware(BaseHTTPMiddleware):
    """Applies the literal VAPT-spec security headers to every ordinary HTTP
    response (routed through FastAPI/Starlette's normal middleware stack).

    Unlike the Django side (which renders real HTML/CSS/JS and has to relax
    `Content-Security-Policy` accordingly), this service is pure JSON/
    WebSocket with nothing to render, so the original spec's literal,
    maximally strict policy is used as-is, unmodified. See
    `app/core/ws_security_headers.py` for the WebSocket-handshake equivalent,
    and `apply_security_headers()` above for the one path (unhandled
    exceptions) that bypasses this middleware entirely.
    """

    async def dispatch(
        self, request: Request, call_next: Callable[[Request], Awaitable[Response]]
    ) -> Response:
        response = await call_next(request)
        return apply_security_headers(response)
